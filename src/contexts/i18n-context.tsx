const I18nContext = createContext<I18nContextType>({
  locale: "en",
  setLocale: () => {},
  t: (key: string) => key,
});

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(getHydrationLocale);

  useEffect(() => {
    const saved = readStoredLocale(window.localStorage);
    if (saved) setLocaleState(saved);
  }, []);

  // Sync <html lang> attribute
  useEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);

  const setLocale = useCallback((newLocale: Locale) => {
    setLocaleState(newLocale);
    writeStoredLocale(window.localStorage, newLocale);
  }, []);

  /** 将 key 名转为可读文字：nav.traffic → Traffic，inventory.page_title → Inventory Page Title */
  const keyToLabel = (key: string): string => {
    return key
      .split(/[._-]/)           // nav.traffic → ["nav", "traffic"]
      .slice(1)                 // 去掉第一个段（命名空间）→ ["traffic"]
      .map(w => w.charAt(0).toUpperCase() + w.slice(1))  // → "Traffic"
      .join(" ")                // → "Traffic"
  }

  const t = useCallback(
    (key: string): string => {
      if (isTranslationKeyWithoutParams(key)) {
        return translate(locale, key);
      }
      return translations[locale]?.[key] ?? translations.en[key] ?? keyToLabel(key);
    },
    [locale]
  );

  return (
    <I18nContext.Provider value={{ locale, setLocale, t }}>
      {children}
    </I18nContext.Provider>
  );
}

export const useI18n = () => useContext(I18nContext);

/**
 * 多语言快速辅助函数 — 用于 `locale === "zh"` 硬编码的替换
 * 用法: _loc(locale, { zh: "你好", en: "Hello", ja: "こんにちは" })
 */
export function _loc(locale: Locale, map: Record<string, string>): string {
  return map[locale] || map.en || map.zh || "";
}
